"""Render a human review sheet (REVIEW.md) for a dataset, for owner approval before freezing.

uv run python -m evals.build.review_sheet seeded-v1
"""

from __future__ import annotations

import sys

from evals.dataset import Dataset, GitSource, ItemKind
from watchman_review.gitutil import parse_diff

CONTEXT = 2
MAX_LINES = 24


def excerpt(patch: str, path: str, start: int, end: int) -> str:
    """Head-side lines around [start, end] from the diff, '+' marking added lines."""
    d = parse_diff(patch)
    f = d.file(path)
    if f is None:
        return "(file not in diff)"
    out: list[str] = []
    for h in f.hunks:
        n = h.new_start
        for line in h.lines:
            if line.startswith("-") or line.startswith("\\"):
                continue
            if start - CONTEXT <= n <= end + CONTEXT:
                mark = "+" if line.startswith("+") else " "
                out.append(f"{n:>5} {mark} {line[1:]}")
            n += 1
    if len(out) > MAX_LINES:
        out = [*out[:MAX_LINES], "  ..."]
    return "\n".join(out) or "(no lines)"


def render(name: str) -> str:
    ds = Dataset.load(name)
    items = ds.items()
    lines = [
        f"# Review sheet: {name}",
        "",
        f"{len(items)} items. Approve, or list item ids to drop or fix. Generated by "
        "`python -m evals.build.review_sheet`; not part of the frozen content.",
        "",
    ]
    for it in items:
        src = it.source
        assert isinstance(src, GitSource)
        patch = (ds.item_dir(it.id) / "change.patch").read_text()
        stats = parse_diff(patch)
        lines += [
            f"## {it.id}  ({ds.split_of(it.id).value})",
            "",
            f"- upstream: `{src.repo}@{src.upstream_commit[:10]}`: "
            f"{it.meta.get('upstream_subject', '')}",
            f"- task shown to reviewer: {it.task}",
            f"- diff: {len(stats.files)} file(s), +{stats.lines_added}/-{stats.lines_removed}",
        ]
        if it.kind is ItemKind.CLEAN:
            lines += ["- ground truth: no defects (unmodified upstream commit)", ""]
            continue
        for d in it.defects:
            lines += [
                f"- defect: **{d.category.value}** `{d.file}:{d.line_start}-{d.line_end}`: "
                f"{d.description}",
            ]
            for alt in d.alt_ranges:
                lines.append(f"  - also acceptable: `{alt.file}:{alt.line_start}-{alt.line_end}`")
            lines += ["", "```", excerpt(patch, d.file, d.line_start, d.line_end), "```", ""]
    return "\n".join(lines) + "\n"


def main() -> None:
    for name in sys.argv[1:] or ["seeded-v1", "reverted-v1", "clean-v1"]:
        out = Dataset.load(name).root / "REVIEW.md"
        out.write_text(render(name))
        print(f"wrote {out}")


if __name__ == "__main__":
    main()
